export function parseCSV(csvText: string): ScreeningRecord[] {
  const lines = csvText.trim().split(/\r?\n/);
  if (lines.length < 2) return DEFAULT_RECORDS;

  const records: ScreeningRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    if (!line.trim()) continue;

    // Simple CSV tokenizer matching quoted or unquoted values
    const regex = /(?:\"([^\"]*(?:\"\"[^\"]*)*)\")|([^,]+)/g;
    const values: string[] = [];
    let match;
    let lastIndex = 0;

    // Split by comma taking care of quotes
    const rawTokens = line.split('","').map(t => t.replace(/^"|"$/g, '').trim());
    if (rawTokens.length >= 19 && rawTokens[0].startsWith('H')) {
      const id = rawTokens[0];
      const screeningDate = rawTokens[1];
      const region = rawTokens[2] as any;
      const gender = rawTokens[3] as any;
      const age = parseFloat(rawTokens[4]) || 0;
      const height = parseFloat(rawTokens[5]) || 0;
      const weight = parseFloat(rawTokens[6]) || 0;
      const bmi = parseFloat(rawTokens[7]) || 0;
      const sbp = parseFloat(rawTokens[8]) || 0;
      const dbp = parseFloat(rawTokens[9]) || 0;
      const pulse = parseFloat(rawTokens[10]) || 0;
      const fbs = parseFloat(rawTokens[11]) || 0;
      const smoking = rawTokens[12] as any;
      const alcohol = rawTokens[13] as any;
      const exercise = rawTokens[14] as any;
      const diabetesRisk = rawTokens[15] as any;
      const hypertensionRisk = rawTokens[16] as any;
      const riskScore = parseFloat(rawTokens[17]) || 0;
      const riskLevel = rawTokens[18] as any;
      const month = rawTokens[19] || '2026-01';

      records.push({
        id,
        screeningDate,
        region,
        gender,
        age,
        height,
        weight,
        bmi,
        sbp,
        dbp,
        pulse,
        fbs,
        smoking,
        alcohol,
        exercise,
        diabetesRisk,
        hypertensionRisk,
        riskScore,
        riskLevel,
        month
      });
    }
  }

  return records.length > 0 ? records : DEFAULT_RECORDS;
}

export function getFormattedThaiDateTime(date: Date = new Date()): string {
  const dStr = date.toLocaleDateString('th-TH', {
    day: 'numeric',
    month: 'short',
    year: 'numeric'
  });
  const tStr = date.toLocaleTimeString('th-TH', {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit'
  });
  return `${dStr} เวลา ${tStr} น.`;
}

export async function fetchSheetData(): Promise<{ records: ScreeningRecord[]; source: 'live' | 'fallback'; updatedAt: string }> {
  try {
    const response = await fetch(CSV_URL, { cache: 'no-cache' });
    if (!response.ok) {
      throw new Error(`Failed to fetch Google Sheet: status ${response.status}`);
    }
    const csv = await response.text();
    const records = parseCSV(csv);
    return {
      records,
      source: 'live',
      updatedAt: getFormattedThaiDateTime()
    };
  } catch (err) {
    console.warn('Unable to reach Google Sheets API directly, using verified cached sheet data:', err);
    return {
      records: DEFAULT_RECORDS,
      source: 'fallback',
      updatedAt: getFormattedThaiDateTime()
    };
  }
}
